package featureplanegen

import (
	"bytes"
	"fmt"
	"go/format"
	"go/parser"
	"go/token"
)

// wireEligibilityCapacity is the number of typed-plane blocker bits in the
// serving uint32 plane mask. The emitter rejects larger inventories rather
// than omitting or truncating a plane (Requirement 1.6).
const wireEligibilityCapacity = 32

// wireEligibilityAccessBridge maps the four accepted SDK request-access
// annotation names to the corresponding core PlaneAccess constant names. This
// is a closed class vocabulary bridge, not an inventory: unknown or
// unclassified values are rejected by manifest extraction before the bridge
// is consulted. No enum casts and no per-plane switch.
var wireEligibilityAccessBridge = map[string]string{
	"RequestBodyCanonicalRequired": "PlaneAccessCanonicalRequired",
	"RequestBodyMetadataOnly":      "PlaneAccessMetadataOnly",
	"RequestBodyResponseOnly":      "PlaneAccessResponseOnly",
	"RequestBodyWireContract":      "PlaneAccessWireContract",
}

// GenerateWireEligibilityCode parses plane_manifest.go source bytes and
// returns the formatted Go code for the core-local serving catalog
// (internal/core/largebody/plane_catalog_generated.go). It reuses the
// existing manifest parse/extraction and closed request-access validation, so
// malformed declarations fail here before any artifact is installed.
func GenerateWireEligibilityCode(manifestBytes []byte) ([]byte, error) {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "plane_manifest.go", manifestBytes, parser.ParseComments)
	if err != nil {
		return nil, fmt.Errorf("parse manifest: %w", err)
	}

	planes, err := extractPlanes(file, manifestBytes)
	if err != nil {
		return nil, fmt.Errorf("extract planes: %w", err)
	}

	if len(planes) > wireEligibilityCapacity {
		return nil, fmt.Errorf("wire eligibility inventory holds %d planes, exceeding %d-bit blocker capacity: remove or classify planes before regenerating",
			len(planes), wireEligibilityCapacity)
	}

	var buf bytes.Buffer
	buf.WriteString("// Code generated by scripts/generate-feature-planes.go. DO NOT EDIT.\n\n")
	buf.WriteString("package largebody\n\n")
	buf.WriteString("// wireEligibilityPlaneOrder is the fixed serving census in StandardPlanes\n")
	buf.WriteString("// manifest order. Bit i of the plane blocker mask names plane i.\n")
	buf.WriteString("var wireEligibilityPlaneOrder = [...]string{\n")
	for _, p := range planes {
		fmt.Fprintf(&buf, "\t%q,\n", p.planeID)
	}
	buf.WriteString("}\n\n")
	buf.WriteString("// WireEligibilityPlaneCount is the closed serving plane census, derived\n")
	buf.WriteString("// from the emitted order so the count cannot drift from the inventory.\n")
	buf.WriteString("const WireEligibilityPlaneCount = len(wireEligibilityPlaneOrder)\n\n")
	buf.WriteString("// standardPlaneV1Access records the V1 request-body access class in\n")
	buf.WriteString("// wireEligibilityPlaneOrder order.\n")
	buf.WriteString("var standardPlaneV1Access = [WireEligibilityPlaneCount]PlaneAccess{\n")
	for _, p := range planes {
		core, ok := wireEligibilityAccessBridge[p.requestAccess]
		if !ok {
			return nil, fmt.Errorf("plane %s: unsupported request access class %q for wire eligibility (expected one of RequestBodyCanonicalRequired, RequestBodyMetadataOnly, RequestBodyResponseOnly, RequestBodyWireContract)",
				p.varName, p.requestAccess)
		}
		fmt.Fprintf(&buf, "\t%s, // %s\n", core, p.planeID)
	}
	buf.WriteString("}\n\n")
	buf.WriteString("// The serving plane mask carries 32 bits. A negative array length makes\n")
	buf.WriteString("// overflow a compile error even if generated data is hand-edited.\n")
	buf.WriteString("var _ [32 - WireEligibilityPlaneCount]struct{}\n")

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated wire eligibility code: %w\n---\n%s\n---", err, buf.String())
	}

	return formatted, nil
}
