func setupRepo(t *testing.T, files map[string]string) {
	t.Helper()
	dir := t.TempDir()
	git := func(args ...string) {
		t.Helper()
		c := exec.Command("git", args...)
		c.Dir = dir
		if b, err := c.CombinedOutput(); err != nil {
			t.Fatalf("git %v: %v %s", args, err, b)
		}
	}
	git("init", "-q")
	for name, body := range files {
		p := filepath.Join(dir, name)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	git("add", "-f", ".")
	t.Chdir(dir)
}

func runText(t *testing.T, args ...string) string {
	t.Helper()
	var b bytes.Buffer
	if err := run(args, &b); err != nil {
		t.Fatal(err)
	}
	return b.String()
}

func runReport(t *testing.T, args ...string) report {
	t.Helper()
	var r report
	if err := json.Unmarshal([]byte(runText(t, append([]string{"-format=json"}, args...)...)), &r); err != nil {
		t.Fatal(err)
	}
	return r
}

func section(t *testing.T, md, title string) string {
	t.Helper()
	_, rest, ok := strings.Cut(md, "## "+title+"\n")
	if !ok {
		t.Fatalf("missing section %q in:\n%s", title, md)
	}
	rest, _, _ = strings.Cut(rest, "\n## ")
	return html.UnescapeString(rest)
}

func TestMarkdownCode(t *testing.T) {
	for _, tc := range []struct{ in, want string }{
		{"a/b.go", "`a/b.go`"},
		{"a`b.go", "``a`b.go``"},
		{" a ", "`  a  `"},
		{"a\nb", "`a\\nb`"},
	} {
		if got := markdownCode(tc.in); got != tc.want {
			t.Errorf("markdownCode(%q) = %q, want %q", tc.in, got, tc.want)
		}
	}
}

func TestCompactQueue(t *testing.T) {
	setupRepo(t, queueFixture)

	md := runText(t)
	for _, want := range []string{
		"Read the source before acting; compact output never quotes comment text.",
		"Files: 5 selected; 1 remaining (6 with comments).",
		"Groups: 8 in selected files.",
		"Excluded files: 2.",
	} {
		if !strings.Contains(md, want) {
			t.Errorf("compact header missing %q:\n%s", want, md)
		}
	}
	if strings.Contains(md, "SENTINEL") {
		t.Fatalf("compact output quoted comment text:\n%s", md)
	}
	for _, tc := range []struct{ title, want string }{
		{"Likely cleanup", "- `b/labels_test.go`: 2 groups, lines 6, 8; hints: test_label\n- `b/mixed.go`: 1 group, lines 3; hints: banner"},
		{"Needs judgment", "- `a/prose.go`: 1 group, lines 3; hints: unknown\n- `b/mixed.go`: 1 group, lines 6; hints: unknown"},
		{"Protected or sensitive", "- `b/mixed.go`: 1 group, lines 9-10; hints: directive"},
	} {
		if got := section(t, md, tc.title); !strings.Contains(got, tc.want) {
			t.Errorf("%s missing %q:\n%s", tc.title, tc.want, got)
		}
	}
	if strings.Contains(section(t, md, "Needs judgment"), "e/prose.go") {
		t.Errorf("compact selected past the default five files:\n%s", md)
	}

	one := runText(t, "-files=1")
	if !strings.Contains(one, "Files: 1 selected; 5 remaining (6 with comments).") || !strings.Contains(one, "Groups: 1 in selected files.") {
		t.Errorf("-files=1 counts wrong:\n%s", one)
	}
	if strings.Contains(section(t, one, "Likely cleanup"), "b/labels_test.go") {
		t.Errorf("-files=1 prioritized cleanup over path order:\n%s", one)
	}
	if !strings.Contains(section(t, one, "Needs judgment"), "- `a/prose.go`: 1 group, lines 3; hints: unknown") {
		t.Errorf("-files=1 did not select the first path:\n%s", one)
	}

	all := runText(t, "-files=0")
	if !strings.Contains(all, "Files: 6 selected; 0 remaining (6 with comments).") || !strings.Contains(all, "Groups: 9 in selected files.") {
		t.Errorf("all-files counts wrong:\n%s", all)
	}
	if !strings.Contains(section(t, all, "Needs judgment"), "- `e/prose.go`: 1 group, lines 3; hints: unknown") {
		t.Errorf("all files missing the last file:\n%s", all)
	}

	detail := runText(t, "-detail")
	for _, want := range []string{"// SENTINEL mixed prose with directive", "//go:noinline", "SENTINEL fifth prose."} {
		if !strings.Contains(detail, want) {
			t.Errorf("detail missing %q:\n%s", want, detail)
		}
	}
}

func TestDetailAndJSONCompatibility(t *testing.T) {
	setupRepo(t, queueFixture)

	full := runReport(t)
	if full.Total != 9 || len(full.Groups) != 9 || full.Next != nil {
		t.Fatalf("default JSON is not the full inventory: %+v", full)
	}
	if full.Groups[0].Path != "a/prose.go" || full.Groups[0].Text != "// SENTINEL first prose." {
		t.Fatalf("JSON group text or order changed: %+v", full.Groups[0])
	}
	page := runReport(t, "-files=2", "-limit=1")
	if page.Total != 3 || len(page.Groups) != 1 || page.Next == nil || *page.Next != 1 || page.Groups[0].Path != "a/prose.go" {
		t.Fatalf("file-bounded pagination: %+v", page)
	}
	next := runReport(t, "-files=2", "-offset=1", "-limit=1")
	if len(next.Groups) != 1 || next.Groups[0].Path != "b/labels_test.go" || next.Groups[0].Text != "// SENTINEL first label" || next.Next == nil || *next.Next != 2 {
		t.Fatalf("second page: %+v", next)
	}
	detail := runText(t, "-detail", "-files=2", "-offset=1", "-limit=1")
	if !strings.Contains(detail, "offset: 1") || !strings.Contains(detail, "// SENTINEL first label") || strings.Contains(detail, "SENTINEL first prose.") {
		t.Fatalf("detail pagination changed:\n%s", detail)
	}
	for _, flag := range []string{"-offset=1", "-limit=1"} {
		var b bytes.Buffer
		if err := run([]string{flag}, &b); err == nil || !strings.Contains(err.Error(), "detail") {
			t.Errorf("compact %s: want pagination error, got %v", flag, err)
		}
	}
}
