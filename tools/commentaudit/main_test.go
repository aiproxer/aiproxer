func TestInventory(t *testing.T) {
	dir := t.TempDir()
	git := func(args ...string) {
		t.Helper()
		c := exec.Command("git", args...)
		c.Dir = dir
		if b, err := c.CombinedOutput(); err != nil {
			t.Fatalf("git: %v: %s", err, b)
		}
	}
	git("init", "-q")
	write := func(name, content string) {
		t.Helper()
		p := filepath.Join(dir, name)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("a/a.go", "//go:build never\n\npackage a\n\n// Exported docs.\n//go:noinline\n//nolint:example // TODO upstream https://example.com\nfunc Exported() { _ = `// not a comment` }\n")
	write("a/generated.go", "// Code generated by test. DO NOT EDIT.\npackage a\n")
	write("vendor/x/v.go", "package x\n// ignored\n")
	write("other.go", "package other\n// warning: check\n")
	git("add", "-f", ".")
	old, err := os.Getwd()
	if err != nil {
		t.Fatal(err)
	}
	if err = os.Chdir(dir); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = os.Chdir(old) })
	get := func(args ...string) report {
		t.Helper()
		var b bytes.Buffer
		if err := run(append([]string{"-format=json"}, args...), &b); err != nil {
			t.Fatal(err)
		}
		var r report
		if err := json.Unmarshal(b.Bytes(), &r); err != nil {
			t.Fatal(err)
		}
		return r
	}
	r := get("-limit=1")
	if r.Total != 3 || len(r.Groups) != 1 || r.Next == nil || *r.Next != 1 || len(r.Excluded) != 2 {
		t.Fatalf("first page: %+v", r)
	}
	next := get("-offset=1", "-limit=1")
	if len(next.Groups) != 1 || next.Groups[0].Symbol != "Exported" {
		t.Fatalf("second page: %+v", next)
	}
	categories := map[string]bool{}
	for _, f := range next.Groups[0].Findings {
		categories[f.Category] = true
	}
	for _, c := range []string{"directive", "lint", "todo", "external_constraint", "public_doc"} {
		if !categories[c] {
			t.Errorf("missing %s: %+v", c, next.Groups[0])
		}
	}
	if next.Groups[0].Fingerprint != get("-offset=1", "-limit=1").Groups[0].Fingerprint {
		t.Error("unstable fingerprint")
	}
	scoped := get("a")
	if scoped.Total != 2 || len(scoped.Excluded) != 1 {
		t.Fatalf("scope: %+v", scoped)
	}
	last := get("-offset=99")
	if len(last.Groups) != 0 || last.Next != nil {
		t.Fatalf("end: %+v", last)
	}
	var md bytes.Buffer
	if err := run([]string{"a"}, &md); err != nil || !strings.Contains(md.String(), "Heuristics are review hints") {
		t.Fatalf("markdown: %v %s", err, md.String())
	}
	write("a/bad.go", "package a\nfunc broken(\n")
	git("add", "a/bad.go")
	if err := run(nil, &bytes.Buffer{}); err == nil || !strings.Contains(err.Error(), "a/bad.go") {
		t.Fatalf("parse error: %v", err)
	}
}

func TestClassifyReviewSignals(t *testing.T) {
	for _, tc := range []struct{ text, category string }{
		{"// Copyright 2025 Example. All rights reserved.", "license"},
		{"// IMPORTANT: do not remove this workaround", "warning"},
		{"// ----", "banner"},
		{"//go:embed assets/*", "directive"},
	} {
		found := false
		for _, f := range classify(tc.text, "") {
			found = found || f.Category == tc.category
		}
		if !found {
			t.Errorf("classify(%q) missing %q", tc.text, tc.category)
		}
	}
}

