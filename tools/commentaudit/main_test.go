func TestReviewRegressions(t *testing.T) {
	dir := t.TempDir()
	git := func(args ...string) {
		t.Helper()
		c := exec.Command("git", args...)
		c.Dir = dir
		if b, e := c.CombinedOutput(); e != nil {
			t.Fatalf("git %v: %v %s", args, e, b)
		}
	}
	git("init", "-q")
	write := func(name, text string) {
		t.Helper()
		p := filepath.Join(dir, name)
		if e := os.MkdirAll(filepath.Dir(p), 0o755); e != nil {
			t.Fatal(e)
		}
		if e := os.WriteFile(p, []byte(text), 0o644); e != nil {
			t.Fatal(e)
		}
	}
	write("clean.go", "package p\n")
	write("evil<img>.go", "package p\n// TODO test\n")
	write("comments.go", "package p\nvar _ = /*same*/ 1 + /*same*/ 2\n/*line virtual.go:1*/ var x = 1\n// TODO <img src=x onerror=alert(1)> [link](https://bad)\n")
	git("add", ".")
	old, _ := os.Getwd()
	if e := os.Chdir(dir); e != nil {
		t.Fatal(e)
	}
	t.Cleanup(func() { _ = os.Chdir(old) })
	if e := run([]string{"clean.go", "missing"}, &bytes.Buffer{}); e == nil {
		t.Error("unmatched scope accepted")
	}
	if e := run([]string{"clean.go"}, &bytes.Buffer{}); e != nil {
		t.Errorf("comment-free scope: %v", e)
	}
	var b bytes.Buffer
	if e := run([]string{"-format=json", "comments.go"}, &b); e != nil {
		t.Fatal(e)
	}
	var r report
	if e := json.Unmarshal(b.Bytes(), &r); e != nil {
		t.Fatal(e)
	}
	if len(r.Groups) < 3 {
		t.Fatalf("groups: %+v", r.Groups)
	}
	if r.Groups[0].Fingerprint == r.Groups[1].Fingerprint {
		t.Error("same-line fingerprints collide")
	}
	found := false
	for _, g := range r.Groups {
		if strings.Contains(g.Text, "/*line ") {
			for _, f := range g.Findings {
				found = found || f.Category == "directive"
			}
		}
	}
	if !found {
		t.Error("block line directive not classified")
	}
	b.Reset()
	if e := run([]string{"evil<img>.go"}, &b); e != nil || strings.Contains(b.String(), "<img>") {
		t.Errorf("unsafe path: %v %s", e, b.String())
	}
	b.Reset()
	if e := run([]string{"comments.go"}, &b); e != nil {
		t.Fatal(e)
	}
	if !strings.Contains(b.String(), "    // TODO <img src=x onerror=alert(1)> [link](https://bad)") || strings.Contains(b.String(), "- **todo**: // TODO") {
		t.Errorf("unsafe or altered markdown: %s", b.String())
	}
}

func TestRejectTrackedSymlinksAndUnmergedPaths(t *testing.T) {
	dir := t.TempDir()
	git := func(args ...string) {
		t.Helper()
		c := exec.Command("git", args...)
		c.Dir = dir
		if b, e := c.CombinedOutput(); e != nil {
			t.Fatalf("git: %v %s", e, b)
		}
	}
	git("init", "-q")
	outside := filepath.Join(t.TempDir(), "outside.go")
	if e := os.WriteFile(outside, []byte("package p\n// secret\n"), 0o644); e != nil {
		t.Fatal(e)
	}
	if e := os.Symlink(outside, filepath.Join(dir, "link.go")); e != nil {
		t.Skip(e)
	}
	git("add", "link.go")
	old, _ := os.Getwd()
	if e := os.Chdir(dir); e != nil {
		t.Fatal(e)
	}
	t.Cleanup(func() { _ = os.Chdir(old) })
	if e := run(nil, &bytes.Buffer{}); e == nil {
		t.Error("tracked symlink accepted")
	}
	git("rm", "--cached", "-q", "link.go")
	if e := os.Mkdir(filepath.Join(dir, "sub"), 0o755); e != nil {
		t.Fatal(e)
	}
	if e := os.WriteFile(filepath.Join(dir, "sub", "file.go"), []byte("package p\n"), 0o644); e != nil {
		t.Fatal(e)
	}
	git("add", "sub/file.go")
	if e := os.Remove(filepath.Join(dir, "sub", "file.go")); e != nil {
		t.Fatal(e)
	}
	if e := os.Remove(filepath.Join(dir, "sub")); e != nil {
		t.Fatal(e)
	}
	if e := os.Symlink(filepath.Dir(outside), filepath.Join(dir, "sub")); e != nil {
		t.Fatal(e)
	}
	if e := run([]string{"sub"}, &bytes.Buffer{}); e == nil {
		t.Error("symlink path component accepted")
	}
	git("rm", "--cached", "-q", "sub/file.go")

	// Index multiple conflict stages for the same path.
	c := exec.Command("git", "hash-object", "-w", "--stdin")
	c.Dir = dir
	c.Stdin = strings.NewReader("package p\n")
	hash, e := c.Output()
	if e != nil {
		t.Fatal(e)
	}
	c = exec.Command("git", "update-index", "--index-info")
	c.Dir = dir
	h := strings.TrimSpace(string(hash))
	c.Stdin = strings.NewReader("100644 " + h + " 1\tconflict.go\n100644 " + h + " 2\tconflict.go\n")
	if out, e := c.CombinedOutput(); e != nil {
		t.Fatalf("index: %v %s", e, out)
	}
	if e := run(nil, &bytes.Buffer{}); e == nil || !strings.Contains(e.Error(), "conflict.go") {
		t.Errorf("unmerged path: %v", e)
	}
}
